def test_build_workbook_uses_custom_primary_color_for_sum_header(seeded_db, tmp_path):
    import openpyxl

    from export.excel_exporter import build_workbook

    seeded_db.set_branding(primary_color="#112233")
    output_path = str(tmp_path / "branded.xlsx")

    build_workbook(seeded_db, output_path)

    wb = openpyxl.load_workbook(output_path)
    ws = wb["SUM"]
    assert ws["A1"].fill.fgColor.rgb.upper().endswith("112233")


