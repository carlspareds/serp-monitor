"""Client-branded exports: logo/colors for PDF and Excel.

Covers:
  - Database.get_branding/set_branding: defaults, CRUD, validation
    (colors outside #rrggbb degrade to the default, never raise).
  - export.pdf_report.build_pdf: with/without logo, with/without narrative
    override (smoke -- same criterion as tests/test_pdf_report.py: no PDF
    text-extraction library in the environment).
  - export.excel_exporter.build_workbook: brand color in the sheet headers.

There is no UI to edit branding (it is set directly via the Database API,
e.g. for white-labeled reports); the values still flow into every export.
"""

import struct
import zlib

from conftest import make_db as _db


def _tiny_png_bytes() -> bytes:
    """Real 1x1 PNG (solid red) -- generated by hand (no Pillow as a test
    dependency), valid for reportlab.lib.utils.ImageReader to read without
    blowing up (brief: 'real minimal 1x1 PNG')."""
    def chunk(tag: bytes, data: bytes) -> bytes:
        body = tag + data
        return struct.pack("!I", len(data)) + body + struct.pack("!I", zlib.crc32(body) & 0xFFFFFFFF)

    sig = b"\x89PNG\r\n\x1a\n"
    ihdr = struct.pack("!IIBBBBB", 1, 1, 8, 2, 0, 0, 0)  # 1x1, 8-bit, RGB
    idat = zlib.compress(b"\x00\xff\x00\x00")  # filter byte + 1 red pixel
    return sig + chunk(b"IHDR", ihdr) + chunk(b"IDAT", idat) + chunk(b"IEND", b"")


# ========================================================================= #
# Database.get_branding / set_branding
# ========================================================================= #
def test_get_branding_returns_sensible_defaults_when_empty(tmp_path):
    db = _db(tmp_path)

    branding = db.get_branding()

    # Defaults IDENTICAL to the colors the PDF already had hardcoded
    # before this feature (pdf_report._DARK/_BLUE) -- without this, a
    # new deployment would change appearance without anyone touching anything.
    assert branding == {
        "logo_path": "", "primary_color": "#14233F",
        "secondary_color": "#1F4E9C", "footer_text": "",
    }


def test_set_branding_then_get_branding_roundtrip(tmp_path):
    db = _db(tmp_path)

    db.set_branding(logo_path="data/branding/logo.png", primary_color="#112233",
                    secondary_color="#445566", footer_text="Confidential — Client X")

    branding = db.get_branding()
    assert branding == {
        "logo_path": "data/branding/logo.png", "primary_color": "#112233",
        "secondary_color": "#445566", "footer_text": "Confidential — Client X",
    }


def test_set_branding_invalid_primary_color_degrades_to_default(tmp_path):
    db = _db(tmp_path)

    db.set_branding(primary_color="not-a-color")

    assert db.get_branding()["primary_color"] == "#14233F"


def test_set_branding_invalid_secondary_color_degrades_to_default(tmp_path):
    db = _db(tmp_path)

    db.set_branding(secondary_color="javascript:alert(1)")

    assert db.get_branding()["secondary_color"] == "#1F4E9C"


def test_set_branding_rejects_hex_without_hash_or_wrong_length(tmp_path):
    """Strict #rrggbb: without '#', with fewer/more digits, or extra
    uppercase -- anything that doesn't match the regex degrades, is never
    saved as-is (could break HexColor()/PatternFill in the export)."""
    db = _db(tmp_path)

    db.set_branding(primary_color="14233F")  # no '#'
    assert db.get_branding()["primary_color"] == "#14233F"

    db.set_branding(primary_color="#1423")  # short
    assert db.get_branding()["primary_color"] == "#14233F"


def test_set_branding_none_fields_leave_existing_values_untouched(tmp_path):
    """None = don't touch -- a branding POST without a new logo must not
    erase the current logo (brief: the /report-settings form always
    resends colors/footer, but the file is optional)."""
    db = _db(tmp_path)
    db.set_branding(logo_path="data/branding/logo.png", primary_color="#112233",
                    secondary_color="#445566", footer_text="Footer A")

    db.set_branding(footer_text="Footer B")  # logo_path/colores no pasados

    branding = db.get_branding()
    assert branding["logo_path"] == "data/branding/logo.png"
    assert branding["primary_color"] == "#112233"
    assert branding["secondary_color"] == "#445566"
    assert branding["footer_text"] == "Footer B"


def test_branding_migration_creates_table(tmp_path):
    db = _db(tmp_path)
    conn = db._connect()
    cur = conn.cursor()
    cur.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='branding'")
    row = cur.fetchone()
    conn.close()
    assert row is not None


