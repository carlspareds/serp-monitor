def test_build_pdf_with_logo_and_narrative_override_builds(seeded_db, tmp_path, monkeypatch):
    """logo_path is resolved against pdf_report._project_root -- monkeypatched
    to tmp_path so the test does NOT write into the real repo."""
    from pathlib import Path

    from export import pdf_report as pdf_module

    monkeypatch.setattr(pdf_module, "_project_root", tmp_path)
    logo_dir = tmp_path / "data" / "branding"
    logo_dir.mkdir(parents=True)
    (logo_dir / "logo.png").write_bytes(_tiny_png_bytes())
    seeded_db.set_branding(logo_path="data/branding/logo.png", primary_color="#336699",
                           footer_text="Prepared for Client X — confidential")

    output_path = str(tmp_path / "with_branding.pdf")
    result = pdf_module.build_pdf(seeded_db, output_path,
                                  narrative_override="Overall reputation is stable this month.")

    assert result == output_path
    assert Path(output_path).stat().st_size > 0


